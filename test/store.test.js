import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Worker } from 'node:worker_threads';
const mod = await import('../src/store.js').catch(() => ({}));

test('store implements the approved access lifecycle', async t => {
  assert.equal(typeof mod.ArtifactStore, 'function', 'ArtifactStore is implemented');
  const dir = mkdtempSync(join(tmpdir(), 'artifacts-'));
  let now = 1000;
  const options = { file: join(dir, 'test.sqlite'), now: () => now, claimMs: 100, readMs: 200, capacity: 3 };
  const a = new mod.ArtifactStore(options);
  const b = new mod.ArtifactStore(options);
  t.after(() => { a.close(); b.close(); rmSync(dir, { recursive: true }); });
  const item = a.create({ title: 'Plan', markdown: '# Secret', owner: 'session:a' });
  assert.match(item.token, /^[A-Za-z0-9_-]{43}$/);
  assert.equal(a.get(item.token).kind, 'unclaimed');
  const [one, two] = await Promise.all([Promise.resolve().then(() => a.claim(item.token)), Promise.resolve().then(() => b.claim(item.token))]);
  assert.equal([one, two].filter(Boolean).length, 1, 'exactly one connection wins');
  const session = one || two;
  assert.equal(a.get(item.token), null);
  assert.equal(a.get(item.token, 'incorrect'), null);
  assert.equal(b.get(item.token, session).markdown, '# Secret');
  assert.equal(a.revoke(item.id, 'session:b'), false);
  assert.equal(a.revoke(item.id, 'session:a'), true);
  assert.equal(b.get(item.token, session), null);
  now += 10;
  const pending = a.create({ title: 'Expiry', markdown: 'text', owner: 'a' });
  now += 100;
  assert.equal(b.claim(pending.token), null, 'claim deadline is exclusive');
  const claimed = a.create({ title: 'Read expiry', markdown: 'body', owner: 'a' });
  const browser = a.claim(claimed.token);
  now += 199;
  assert.equal(b.get(claimed.token, browser).markdown, 'body');
  now++;
  assert.equal(b.get(claimed.token, browser), null);
  assert.equal(a.cleanup(), 1, 'creation already removed the expired unclaimed artifact');
});

test('store persists claims and enforces size/capacity', t => {
  assert.equal(typeof mod.ArtifactStore, 'function', 'ArtifactStore is implemented');
  const dir = mkdtempSync(join(tmpdir(), 'artifacts-'));
  const file = join(dir, 'test.sqlite');
  t.after(() => rmSync(dir, { recursive: true }));
  let store = new mod.ArtifactStore({ file, capacity: 1 });
  assert.throws(() => store.create({ title: 'x', markdown: 'a'.repeat(262145), owner: 'a' }), /large/i);
  const item = store.create({ title: 'x', markdown: 'body', owner: 'a' });
  const session = store.claim(item.token);
  assert.throws(() => store.create({ title: 'x', markdown: 'body', owner: 'a' }), /capacity/i);
  store.close();
  store = new mod.ArtifactStore({ file });
  assert.equal(store.get(item.token, session).markdown, 'body');
  assert.equal(store.get(item.token), null);
  store.close();
});

test('independent workers racing for a claim have exactly one winner', async t => {
  assert.equal(typeof mod.ArtifactStore, 'function');
  const dir = mkdtempSync(join(tmpdir(), 'art-race-'));
  const file = join(dir, 'db.sqlite');
  const store = new mod.ArtifactStore({ file });
  t.after(() => { store.close(); rmSync(dir, { recursive: true }); });
  const item = store.create({ title: 'Concurrent', markdown: 'secret', owner: 'a' });
  const gate = new SharedArrayBuffer(4);
  const source = `const {parentPort,workerData}=require('node:worker_threads');
    (async()=>{const {ArtifactStore}=await import(workerData.module);
    const store=new ArtifactStore({file:workerData.file});
    parentPort.postMessage('ready');
    Atomics.wait(new Int32Array(workerData.gate),0,0);
    parentPort.postMessage(store.claim(workerData.token)); store.close();})();`;
  const workers = [0, 1].map(() => new Worker(source, { eval: true, workerData: { file, gate, token: item.token, module: new URL('../src/store.js', import.meta.url).href } }));
  t.after(() => Promise.all(workers.map(w => w.terminate())));
  await Promise.all(workers.map(w => new Promise((resolve, reject) => { w.once('message', resolve); w.once('error', reject); })));
  const pending = workers.map(w => new Promise((resolve, reject) => { w.once('message', resolve); w.once('error', reject); }));
  Atomics.store(new Int32Array(gate), 0, 1);
  Atomics.notify(new Int32Array(gate), 0, 2);
  const sessions = await Promise.all(pending);
  assert.equal(sessions.filter(Boolean).length, 1);
  assert.equal(store.get(item.token, sessions.find(Boolean)).markdown, 'secret');
});

test('tunnel deadline caps pending and claimed artifacts and survives reopening', t => {
  const dir = mkdtempSync(join(tmpdir(), 'art-deadline-'));
  t.after(() => rmSync(dir, { recursive: true }));
  const file = join(dir, 'db');
  let now = 1000;
  let store = new mod.ArtifactStore({ file, now: () => now });
  const pending = store.create({ title: 'Pending', markdown: 'private', owner: 'a', expiresAt: 2000 });
  const item = store.create({ title: 'Read', html: '<p>private</p>', owner: 'a', expiresAt: 2000 });
  const session = store.claim(item.token);
  assert.equal(store.get(item.token, session).readUntil, 2000);
  store.close();
  store = new mod.ArtifactStore({ file, now: () => now });
  t.after(() => store.close());
  now = 2000;
  assert.equal(store.get(item.token, session), null);
  assert.equal(store.get(pending.token), null);
  assert.equal(store.claim(pending.token), null);
  assert.throws(() => store.create({ title: 'Expired', markdown: 'x', owner: 'a', expiresAt: now }), /deadline/i);
});
