import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { ArtifactStore } from '../src/store.js';
const mod = await import('../src/http.js').catch(() => ({}));

test('HTTP preview, claim, refresh, race, denial, expiry and revocation', async t => {
  assert.equal(typeof mod.createHandler, 'function', 'HTTP handler is implemented');
  const dir = mkdtempSync(join(tmpdir(), 'art-http-'));
  let now = 100;
  const store = new ArtifactStore({ file: join(dir, 'db.sqlite'), now: () => now, claimMs: 1000, readMs: 1000 });
  let handler;
  const server = createServer((req, res) => handler(req, res));
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const origin = `http://127.0.0.1:${server.address().port}`;
  handler = mod.createHandler({ store, origin, secure: false });
  t.after(async () => { await new Promise(resolve => server.close(resolve)); store.close(); rmSync(dir, { recursive: true }); });
  const make = () => store.create({ title: 'PRIVATE TITLE', markdown: '# PRIVATE BODY\n\n| A | B |\n|---|---|\n| 1 | 2 |\n\n<script>alert(1)</script>\n\n[x](javascript:alert(1))\n\n![x](https://tracker.invalid/pixel)\n\n```mermaid\ngraph TD; A-->B\n```', owner: 'owner' });
  const item = make();
  const path = `/artifacts/${item.token}`;
  const request = (p = path, opts = {}) => fetch(origin + p, { redirect: 'manual', ...opts });
  const head = await request(path, { method: 'HEAD' });
  assert.equal(head.status, 200);
  assert.equal(head.headers.get('set-cookie'), null);
  const preview = await request();
  assert.equal(preview.status, 200);
  assert.equal(preview.headers.get('cache-control'), 'no-store');
  assert.equal(preview.headers.get('referrer-policy'), 'same-origin', 'same-origin form POST must retain Origin in Chromium');
  const page = await preview.text();
  assert.ok(!page.includes('PRIVATE'));
  assert.match(page, /src="\/artifacts\/assets\/claim.js"/, 'opening a real browser automatically claims without another click');
  const claimAsset = await request('/artifacts/assets/claim.js');
  assert.equal(claimAsset.status, 200);
  assert.match(await claimAsset.text(), /requestSubmit/);
  const nonce = /name="nonce" value="([A-Za-z0-9_-]+)"/.exec(page)[1];
  const preCookie = preview.headers.get('set-cookie').split(';')[0];
  const anotherTab = await request(path, { headers: { cookie: preCookie } });
  assert.ok((await anotherTab.text()).includes(`name="nonce" value="${nonce}"`), 'same-browser tabs share a claim nonce');
  const claim = (token = item.token, overrides = {}) => request(`/artifacts/${token}/claim`, { method: 'POST', headers: { origin, cookie: preCookie, 'content-type': 'application/x-www-form-urlencoded', ...overrides }, body: new URLSearchParams({ nonce }) });
  assert.equal((await claim(item.token, { origin: 'https://evil.invalid' })).status, 404);
  assert.equal((await claim(item.token, { cookie: '' })).status, 404);
  const results = await Promise.all([claim(), claim()]);
  assert.deepEqual(results.map(x => x.status).sort(), [303, 404]);
  const winner = results.find(x => x.status === 303);
  const cookie = winner.headers.get('set-cookie').split(';')[0];
  assert.match(winner.headers.get('set-cookie'), /HttpOnly/);
  assert.match(winner.headers.get('set-cookie'), /SameSite=Strict/);
  assert.equal((await request()).status, 404);
  for (let n = 0; n < 2; n++) {
    const view = await request(path, { headers: { cookie } });
    assert.equal(view.status, 200);
    const html = await view.text();
    assert.match(html, /PRIVATE BODY/);
    assert.match(html, /<table>/);
    assert.match(html, /class="mermaid"/);
    assert.ok(!html.includes('<script>alert'));
    assert.ok(!html.includes('href="javascript:'));
    assert.ok(!html.includes('<img'));
    assert.match(view.headers.get('content-security-policy'), /frame-ancestors 'none'/);
  }
  const unknown = await request('/artifacts/' + 'x'.repeat(43));
  assert.equal(await unknown.text(), await (await request()).text());
  now += 1000;
  assert.equal((await request(path, { headers: { cookie } })).status, 404);
  const revoked = make();
  store.revoke(revoked.id, 'owner');
  assert.equal((await request(`/artifacts/${revoked.token}`)).status, 404);
});

test('production cookies are secure and scoped to the individual artifact', async () => {
  assert.equal(typeof mod.createHandler, 'function');
  const token = 'a'.repeat(43);
  const headers = new Map();
  const res = { setHeader: (key, value) => headers.set(key, value), end() {} };
  const handler = mod.createHandler({ store: { get: () => ({ kind: 'unclaimed' }) }, origin: 'https://review.example.com' });
  await handler({ url: `/artifacts/${token}`, method: 'GET', headers: {} }, res);
  assert.match(headers.get('Set-Cookie'), /; Secure$/);
  assert.ok(headers.get('Set-Cookie').includes(`Path=/artifacts/${token};`));
  assert.ok(!headers.get('Set-Cookie').includes('Domain='));
  assert.ok(!headers.get('Set-Cookie').includes('Max-Age='));
});
